import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";

import { z } from "zod";

// `pnpm env:local` — writes .env.local from the running local Supabase stack.
// Refuses to overwrite an existing file unless --force is passed. Never prints values.

const statusSchema = z.object({
  API_URL: z.url(),
  DB_URL: z.url(),
  PUBLISHABLE_KEY: z.string().min(20),
  SECRET_KEY: z.string().min(20),
});

const TARGET = ".env.local";

function main(): number {
  if (existsSync(TARGET) && !process.argv.includes("--force")) {
    console.error(`${TARGET} already exists. Re-run with --force to overwrite it.`);
    return 1;
  }

  let raw: string;
  try {
    raw = execFileSync("supabase", ["status", "-o", "json"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
  } catch {
    console.error("Local Supabase is not running. Start it with `pnpm db:start` first.");
    return 1;
  }

  const status = statusSchema.safeParse(JSON.parse(raw));
  if (!status.success) {
    console.error("Unexpected `supabase status` output; fill .env.local manually from .env.example.");
    return 1;
  }
  const s = status.data;

  const lines = [
    "# Local development env — generated by `pnpm env:local`. Never commit.",
    "NEXT_PUBLIC_APP_URL=http://localhost:3000",
    `NEXT_PUBLIC_SUPABASE_URL=${s.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${s.PUBLISHABLE_KEY}`,
    `SUPABASE_SECRET_KEY=${s.SECRET_KEY}`,
    `DATABASE_URL=${s.DB_URL}`,
    `DIRECT_URL=${s.DB_URL}`,
    "",
  ];
  writeFileSync(TARGET, lines.join("\n"), { mode: 0o600 });
  console.log(`Wrote ${TARGET}. Verify with: pnpm db:check`);
  return 0;
}

process.exit(main());
